"""scene.json → URDF、SDF（Gazebo world）、USD。

三種格式都從同一份中介表示產生，元素與零件一一對應：
- 每個元素一個 link（URDF、SDF）或 Xform（USD），位姿是元素位姿；
- 每個零件一組 visual 與 collision（URDF、SDF）或一個 Cube／Mesh prim（USD）。
匯出座標：frame=scene 時地面在 z=0；frame=input 時根節點帶 T_scene_from_input 的反變換，幾何回到原始點雲座標。
"""
from __future__ import annotations

import hashlib
import math
import re
import shutil
from pathlib import Path
from xml.sax.saxutils import quoteattr

import numpy as np

from .geometry import inv_T, pose_T, rpy_from_R
from .mesh import read_stl

KIND_COLOR = {"floor": (0.55, 0.55, 0.55), "ceiling": (0.9, 0.9, 0.9), "wall": (0.82, 0.79, 0.72),
              "mesh": (0.45, 0.6, 0.75)}


def class_color(el):
    if el["kind"] in KIND_COLOR:
        return KIND_COLOR[el["kind"]]
    h = hashlib.sha256(el["class"].encode()).digest()
    return tuple(round(0.25 + 0.6 * b / 255, 3) for b in h[:3])


def root_T(scene, frame):
    if frame == "scene":
        return np.eye(4)
    if frame == "input":
        return inv_T(np.asarray(scene["frame"]["T_scene_from_input"], float))
    raise ValueError("frame must be scene or input")


def elem_T(el):
    return pose_T(el["pose"]["xyz"], el["pose"]["yaw"])


def exported(scene):
    return [el for el in scene["elements"] if el.get("export", True)]


def _fmt(v):
    return " ".join(f"{x:.6g}" if abs(x) > 1e-12 else "0" for x in v)


def _xyz_rpy(T):
    return _fmt(T[:3, 3]), _fmt(rpy_from_R(T[:3, :3]))


def _mesh_uri(out_dir, rel, mode):
    if mode == "relative":
        return rel
    if mode == "file":
        return "file://" + str((Path(out_dir) / rel).resolve())
    if mode.startswith("package:"):
        return f"package://{mode.split(':', 1)[1]}/{rel}"
    raise ValueError("mesh_uri must be relative, file or package:<name>")


def _safe(name):
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return s if re.match(r"[A-Za-z_]", s) else "_" + s


def _collides(el, part):
    return not (part["type"] == "mesh" and el.get("collision") is False)


# ------------------------------------------------------------------ URDF

def write_urdf(scene, out_dir, path, frame="scene", mesh_uri="relative"):
    rT = root_T(scene, frame)
    xyz, rpy = _xyz_rpy(rT)
    L = ['<?xml version="1.0"?>', '<robot name="scene">',
         '  <!-- generated by pcd2scene; static scene: every link is fixed to world -->',
         '  <link name="world"/>']
    inertial = ('    <inertial><mass value="1"/>'
                '<inertia ixx="0.001" ixy="0" ixz="0" iyy="0.001" iyz="0" izz="0.001"/></inertial>')
    L += ['  <link name="scene_root">', inertial, '  </link>',
          f'  <joint name="world_to_scene" type="fixed"><parent link="world"/><child link="scene_root"/>'
          f'<origin xyz="{xyz}" rpy="{rpy}"/></joint>']
    mats = {}
    for el in exported(scene):
        mats.setdefault(el["class"], class_color(el))
    for name, c in sorted(mats.items()):
        L.append(f'  <material name={quoteattr("m_" + _safe(name))}><color rgba="{_fmt(c)} 1"/></material>')
    for el in exported(scene):
        name = _safe(el["id"])
        L.append(f'  <link name="{name}">')
        for i, p in enumerate(el["parts"]):
            pxyz = _fmt(p["xyz"])
            if p["type"] == "box":
                geo = f'<box size="{_fmt(p["size"])}"/>'
            else:
                geo = f'<mesh filename={quoteattr(_mesh_uri(out_dir, p["file"], mesh_uri))} scale="{_fmt(p["scale"])}"/>'
            L.append(f'    <visual name="{name}_v{i}"><origin xyz="{pxyz}" rpy="0 0 0"/><geometry>{geo}</geometry>'
                     f'<material name={quoteattr("m_" + _safe(el["class"]))}/></visual>')
            if _collides(el, p):
                L.append(f'    <collision name="{name}_c{i}"><origin xyz="{pxyz}" rpy="0 0 0"/>'
                         f'<geometry>{geo}</geometry></collision>')
        L += [inertial, '  </link>']
        exyz, erpy = _xyz_rpy(elem_T(el))
        L.append(f'  <joint name="{name}_joint" type="fixed"><parent link="scene_root"/><child link="{name}"/>'
                 f'<origin xyz="{exyz}" rpy="{erpy}"/></joint>')
    L += ['  <gazebo><static>true</static></gazebo>', '</robot>', '']
    Path(path).write_text("\n".join(L), encoding="utf-8")


# ------------------------------------------------------------------ SDF

def write_sdf(scene, out_dir, path, frame="scene", mesh_uri="relative"):
    rT = root_T(scene, frame)
    L = ['<?xml version="1.0"?>', '<sdf version="1.9">', '  <world name="scene">',
         '    <!-- generated by pcd2scene -->',
         '    <light type="directional" name="sun"><cast_shadows>true</cast_shadows>'
         '<pose>0 0 10 0 0 0</pose><diffuse>0.8 0.8 0.8 1</diffuse><specular>0.2 0.2 0.2 1</specular>'
         '<direction>-0.5 0.1 -0.9</direction></light>',
         '    <model name="scene">', '      <static>true</static>',
         f'      <pose>{_fmt(rT[:3, 3])} {_fmt(rpy_from_R(rT[:3, :3]))}</pose>']
    for el in exported(scene):
        name = _safe(el["id"])
        eT = elem_T(el)
        c = class_color(el)
        L.append(f'      <link name="{name}"><pose>{_fmt(eT[:3, 3])} {_fmt(rpy_from_R(eT[:3, :3]))}</pose>')
        for i, p in enumerate(el["parts"]):
            if p["type"] == "box":
                geo = f'<box><size>{_fmt(p["size"])}</size></box>'
            else:
                geo = (f'<mesh><uri>{_mesh_uri(out_dir, p["file"], mesh_uri)}</uri>'
                       f'<scale>{_fmt(p["scale"])}</scale></mesh>')
            pose = f'<pose>{_fmt(p["xyz"])} 0 0 0</pose>'
            if _collides(el, p):
                L.append(f'        <collision name="c{i}">{pose}<geometry>{geo}</geometry></collision>')
            L.append(f'        <visual name="v{i}">{pose}<geometry>{geo}</geometry>'
                     f'<material><ambient>{_fmt(c)} 1</ambient><diffuse>{_fmt(c)} 1</diffuse></material></visual>')
        L.append('      </link>')
    L += ['    </model>', '  </world>', '</sdf>', '']
    Path(path).write_text("\n".join(L), encoding="utf-8")


# ------------------------------------------------------------------ USD

def _gf(T):
    from pxr import Gf
    return Gf.Matrix4d(*[float(v) for v in np.asarray(T).T.reshape(-1)])   # USD 用列向量，存轉置


def write_usd(scene, out_dir, path, frame="scene"):
    from pxr import Sdf, Usd, UsdGeom, UsdPhysics, Vt

    stage = Usd.Stage.CreateNew(str(path))
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    world = UsdGeom.Xform.Define(stage, "/World")
    stage.SetDefaultPrim(world.GetPrim())
    world.GetPrim().SetCustomDataByKey("generator", f"pcd2scene {scene['tool']['version']}")
    root = UsdGeom.Xform.Define(stage, "/World/Scene")
    root.AddTransformOp().Set(_gf(root_T(scene, frame)))
    mesh_cache = {}
    for el in exported(scene):
        ep = f"/World/Scene/{_safe(el['id'])}"
        ex = UsdGeom.Xform.Define(stage, ep)
        ex.AddTransformOp().Set(_gf(elem_T(el)))
        ex.GetPrim().SetCustomDataByKey("pcd2scene:class", el["class"])
        ex.GetPrim().SetCustomDataByKey("pcd2scene:kind", el["kind"])
        color = Vt.Vec3fArray([class_color(el)])
        for i, p in enumerate(el["parts"]):
            pp = f"{ep}/p{i}"
            if p["type"] == "box":
                g = UsdGeom.Cube.Define(stage, pp)
                g.CreateSizeAttr(1.0)
                T = np.eye(4)
                T[:3, 3] = p["xyz"]
                T[:3, :3] = np.diag(p["size"])
                g.AddTransformOp().Set(_gf(T))
            else:
                src = Path(out_dir) / p["file"]
                if src not in mesh_cache:
                    mesh_cache[src] = read_stl(src)
                v, t = mesh_cache[src]
                g = UsdGeom.Mesh.Define(stage, pp)
                g.CreatePointsAttr(Vt.Vec3fArray.FromNumpy(np.ascontiguousarray(v, np.float32)))
                g.CreateFaceVertexCountsAttr(Vt.IntArray.FromNumpy(np.full(len(t), 3, np.int32)))
                g.CreateFaceVertexIndicesAttr(Vt.IntArray.FromNumpy(np.ascontiguousarray(t.reshape(-1), np.int32)))
                g.CreateSubdivisionSchemeAttr(UsdGeom.Tokens.none)
                T = np.eye(4)
                T[:3, 3] = p["xyz"]
                T[:3, :3] = np.diag(p["scale"])
                g.AddTransformOp().Set(_gf(T))
            g.CreateDisplayColorAttr(color)
            if _collides(el, p):
                UsdPhysics.CollisionAPI.Apply(g.GetPrim())
                if p["type"] == "mesh":
                    UsdPhysics.MeshCollisionAPI.Apply(g.GetPrim()).CreateApproximationAttr(UsdPhysics.Tokens.none)
    stage.GetRootLayer().Save()


def copy_mesh_assets(scene, out_dir, catalog_dir):
    """目錄裡 model.type=mesh 的外部網格複製到 out_dir/meshes/，零件路徑改成相對路徑。"""
    for el in scene["elements"]:
        for p in el["parts"]:
            if p["type"] == "mesh" and not p["file"].startswith("meshes/"):
                src = Path(p["file"])
                if not src.is_absolute():
                    src = Path(catalog_dir) / src
                if src.suffix.lower() != ".stl":
                    raise ValueError(f"mesh asset must be binary STL: {src}")
                dst = Path(out_dir) / "meshes" / src.name
                dst.parent.mkdir(parents=True, exist_ok=True)
                if not dst.exists():
                    shutil.copyfile(src, dst)
                p["file"] = f"meshes/{src.name}"


def export_all(scene, out_dir, formats, frame="scene", mesh_uri="relative"):
    out_dir = Path(out_dir)
    written = []
    for f in formats:
        if f == "urdf":
            write_urdf(scene, out_dir, out_dir / "scene.urdf", frame, mesh_uri)
            written.append("scene.urdf")
        elif f == "sdf":
            write_sdf(scene, out_dir, out_dir / "scene.sdf", frame, mesh_uri)
            written.append("scene.sdf")
        elif f == "usd":
            write_usd(scene, out_dir, out_dir / "scene.usda", frame)
            written.append("scene.usda")
        else:
            raise ValueError(f"unknown format: {f}")
    return written
